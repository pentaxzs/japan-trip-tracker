import { TodoItem, TodosByPhase } from "./types";

function createTodo(text: string): TodoItem {
  return {
    id: crypto.randomUUID(),
    text,
    completed: false,
    category: "default",
    createdAt: new Date().toISOString(),
    completedAt: null,
  };
}

